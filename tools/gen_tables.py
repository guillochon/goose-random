"""Writes tables.goose: the ziggurat tables for the normal and exponential
samplers, and the log-factorials the discrete samplers use.

Everything is computed in 60-digit arithmetic with mpmath and rounded once to
the nearest double (or, for the integer acceptance bounds, floored), so each
entry is the correctly rounded value of its definition.

    python tools/gen_tables.py          (writes tables.goose beside random.goose)
"""
import io
import os
import sys
import mpmath as mp

mp.mp.dps = 60
N = 256


def ziggurat(f, finv, tail_area, lo, hi):
    """Edges X[0..N] of an N-layer ziggurat for the decreasing density f.

    Layer 0 is the base: the rectangle [0, r] x [0, f(r)] plus the tail past
    r, whose total area v is given the width X[0] = v / f(r). Layer i >= 1 is
    the rectangle of width X[i] from height f(X[i]) up to f(X[i+1]), each of
    area v. r is the root that makes the top layer end at X[N] = 0.
    """
    def edges(r):
        v = r * f(r) + tail_area(r)
        x = [v / f(r), r]
        for _ in range(2, N):
            y = v / x[-1] + f(x[-1])
            if y >= f(0):
                return x, v, y - f(0)
            x.append(finv(y))
        return x, v, v / x[-1] + f(x[-1]) - f(0)

    r = mp.findroot(lambda r: edges(r)[2], (lo, hi), solver='anderson')
    x, v, miss = edges(r)
    assert len(x) == N and abs(miss) < mp.mpf(10) ** -50, (len(x), miss)
    return r, v, x + [mp.mpf(0)]


def normal():
    f = lambda x: mp.exp(-x * x / 2)
    finv = lambda y: mp.sqrt(-2 * mp.log(y))
    tail = lambda r: mp.sqrt(mp.pi / 2) * mp.erfc(r / mp.sqrt(2))
    return ziggurat(f, finv, tail, mp.mpf('3.6'), mp.mpf('3.7'))


def exponential():
    f = lambda x: mp.exp(-x)
    finv = lambda y: -mp.log(y)
    tail = lambda r: mp.exp(-r)
    return ziggurat(f, finv, tail, mp.mpf('7.6'), mp.mpf('7.8'))


def dbl(x):
    s = repr(float(x))
    return s if ('.' in s or 'e' in s) else s + '.0'


def emit(name, typ, vals, per_line):
    print(f'let {name}: {typ}[{len(vals)}] = [')
    for i in range(0, len(vals), per_line):
        print('    ' + ', '.join(vals[i:i + per_line]) + ',')
    print('];')
    print()


def main():
    print('// Generated by tools/gen_tables.py; do not edit.')
    print('//')
    print('// Ziggurat tables for 256 layers (see random.goose) and log-factorials,')
    print('// each the correctly rounded double of its exact value.')
    print()
    print('namespace random;')
    print()

    for tag, (r, v, x), bits, f in (
        ('NORM', normal(), 52, lambda t: mp.exp(-t * t / 2)),
        ('EXP', exponential(), 53, lambda t: mp.exp(-t)),
    ):
        scale = mp.mpf(2) ** bits
        k = [str(int(mp.floor(scale * x[i + 1] / x[i]))) for i in range(N)]
        w = [dbl(x[i] / scale) for i in range(N)]
        fv = [dbl(f(x[i])) for i in range(N + 1)]
        print(f'// r = {mp.nstr(r, 25)}, layer area v = {mp.nstr(v, 25)}.')
        print(f'let ZIG_{tag}_R = {dbl(r)};')
        print(f'let ZIG_{tag}_INV_R = {dbl(1 / r)};')
        print()
        print(f'// A draw of {bits} bits m in layer i lies under the next layer, and is')
        print(f'// accepted at once, when m < ZIG_{tag}_K[i] = floor(2^{bits} X[i+1] / X[i]).')
        emit(f'ZIG_{tag}_K', 'u64', k, 4)
        print(f'// X[i] / 2^{bits}: m times it is the abscissa, uniform on [0, X[i]).')
        emit(f'ZIG_{tag}_W', 'f64', w, 4)
        print(f'// The density, unnormalized, at each edge: F[i] = f(X[i]).')
        emit(f'ZIG_{tag}_F', 'f64', fv, 4)

    print('// log(k!) for k < 128.')
    emit('LOG_FACT', 'f64', [dbl(mp.log(mp.factorial(k))) for k in range(128)], 4)

    # Stirling's correction log(k!) - [(k + 1/2) log(k + 1) - (k + 1) + log(2 pi)/2],
    # which BTRS (Hormann 1993) uses for k < 10.
    fc = []
    for k in range(10):
        kk = mp.mpf(k)
        fc.append(dbl(mp.log(mp.factorial(k)) - ((kk + mp.mpf(1) / 2) * mp.log(kk + 1)
                                                  - (kk + 1) + mp.log(2 * mp.pi) / 2)))
    print('// Stirling\'s correction to log(k!) at k + 1, for k < 10:')
    print('// log(k!) - ((k + 1/2) log(k + 1) - (k + 1) + log(2 pi) / 2).')
    emit('STIRLING_FC', 'f64', fc, 4)


if __name__ == '__main__':
    buf = io.StringIO()
    sys.stdout = buf
    main()
    sys.stdout = sys.__stdout__
    path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'tables.goose')
    with open(path, 'w', newline='\n') as f:
        f.write(buf.getvalue().rstrip('\n') + '\n')
